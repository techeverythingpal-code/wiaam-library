-- 002_copy_numbers.sql
-- Copies get a number inside their book: book 5 -> copies 5-1, 5-2, 5-3.
-- copy_id becomes an internal number created by the database.
-- Safe to run more than once.

BEGIN;

-- 1) Counter on each book: the next copy number to hand out.
--    It only goes up, so a deleted number is never reused.
ALTER TABLE book
    ADD COLUMN IF NOT EXISTS next_copy_number INTEGER NOT NULL DEFAULT 1;

-- 2) The copy's number inside its book (1, 2, 3 ...).
ALTER TABLE book_copy
    ADD COLUMN IF NOT EXISTS copy_number INTEGER;

-- 3) Number any copies that already exist (per book, oldest first).
UPDATE book_copy c
SET copy_number = r.rn
FROM (
    SELECT copy_id,
           ROW_NUMBER() OVER (PARTITION BY book_id ORDER BY copy_id) AS rn
    FROM book_copy
) r
WHERE c.copy_id = r.copy_id AND c.copy_number IS NULL;

ALTER TABLE book_copy ALTER COLUMN copy_number SET NOT NULL;

-- 4) The same number can never appear twice in one book.
CREATE UNIQUE INDEX IF NOT EXISTS book_copy_book_number_uq
    ON book_copy (book_id, copy_number);

-- 5) Set each book's counter after its highest existing copy number.
UPDATE book b
SET next_copy_number = GREATEST(
    b.next_copy_number,
    COALESCE((SELECT MAX(c.copy_number) FROM book_copy c WHERE c.book_id = b.book_id), 0) + 1
);

-- 6) copy_id is now created by the database (no more typing it).
DO $$
DECLARE
    next_id INTEGER;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'book_copy'
          AND column_name = 'copy_id'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE book_copy ALTER COLUMN copy_id ADD GENERATED BY DEFAULT AS IDENTITY;
        SELECT COALESCE(MAX(copy_id), 0) + 1 INTO next_id FROM book_copy;
        EXECUTE format('ALTER TABLE book_copy ALTER COLUMN copy_id RESTART WITH %s', next_id);
    END IF;
END $$;

COMMIT;