-- book        = one row per TITLE (book_id, book_name, auther, age_group, book_cover,
--               next_copy_number)
-- book_copy   = one row per PHYSICAL COPY (below)
-- borrow      = one row per loan; book_id always set, copy_id set when the book has copies

-- Copy label shown in the app: book_id + "-" + copy_number  (book 5, third copy = 5-3)

-- book.next_copy_number: the next copy number to hand out for this book.
-- It only goes up, so a deleted copy number is never reused.
ALTER TABLE book
    ADD COLUMN IF NOT EXISTS next_copy_number INTEGER NOT NULL DEFAULT 1;

-- book_copy: copy_id is an internal number created by the database.
-- copy_number is the 1, 2, 3 ... inside the book, chosen by the system.
CREATE TABLE IF NOT EXISTS book_copy (
    copy_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     INTEGER NOT NULL REFERENCES book(book_id) ON DELETE CASCADE,
    copy_number INTEGER NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS book_copy_book_id_idx ON book_copy (book_id);
CREATE UNIQUE INDEX IF NOT EXISTS book_copy_book_number_uq ON book_copy (book_id, copy_number);

-- borrow points to a copy when the book has copies (see migrations/001 and 002)
ALTER TABLE borrow
    ADD COLUMN IF NOT EXISTS copy_id INTEGER REFERENCES book_copy(copy_id);

CREATE INDEX IF NOT EXISTS borrow_copy_id_idx ON borrow (copy_id);

-- borrow_request: requests sent by visitors from the public home page.
-- A request is for a TITLE (book_id), not a specific copy.
-- NOTE: reconstructed from the code (INSERT/SELECT/UPDATE queries); compare with your real table.
CREATE TABLE IF NOT EXISTS borrow_request (
    request_id     SERIAL PRIMARY KEY,
    book_id        INTEGER NOT NULL REFERENCES book(book_id) ON DELETE CASCADE,
    requester_name VARCHAR(100) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    note           VARCHAR(500),
    status         VARCHAR(10)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS borrow_request_status_idx ON borrow_request (status);